"""Stage 6: deployment exports.

Tree ensembles (XGBoost or scikit-learn RandomForest) are flattened into node tables and
emitted as:
  * C99 (hess_policy.h / hess_policy.c): streaming feature engineering + inference + guardrail,
    no heap, no libm except sqrtf.
  * TypeScript data modules for the web app (frontend/src/lib/hess/generated/*.ts).
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import xgboost as xgb
from sklearn.ensemble import RandomForestRegressor

from .features import LAGS, POLICY_FEATURES


@dataclass
class TreeTable:
    feat: np.ndarray    # int, -1 for leaves
    thr: np.ndarray     # float64
    left: np.ndarray
    right: np.ndarray
    value: np.ndarray   # leaf values
    roots: np.ndarray
    base: float
    scale: float
    cmp_le: bool        # False: fround(x) <  thr (XGBoost); True: fround(x) <= thr (scikit-learn)

    @property
    def n_nodes(self) -> int:
        return int(len(self.feat))

    def predict(self, X: np.ndarray) -> np.ndarray:
        X = np.asarray(X, np.float32).astype(np.float64)
        out = np.full(len(X), 0.0)
        for i, x in enumerate(X):
            s = 0.0
            for r in self.roots:
                n = r
                while self.feat[n] >= 0:
                    xv, t = x[self.feat[n]], self.thr[n]
                    n = self.left[n] if (xv <= t if self.cmp_le else xv < t) else self.right[n]
                s += self.value[n]
            out[i] = self.base + s * self.scale
        return out

    def to_json(self) -> dict:
        return {
            "feat": self.feat.tolist(), "thr": [float(np.float32(t)) if not self.cmp_le else float(t) for t in self.thr],
            "left": self.left.tolist(), "right": self.right.tolist(),
            "value": [float(v) for v in self.value], "roots": self.roots.tolist(),
            "base": self.base, "scale": self.scale, "cmpLe": self.cmp_le,
        }


def table_from_model(model) -> TreeTable:
    feat, thr, left, right, value, roots = [], [], [], [], [], []
    if isinstance(model, xgb.XGBRegressor):
        raw = json.loads(model.get_booster().save_raw("json"))
        trees = raw["learner"]["gradient_booster"]["model"]["trees"]
        base = float(str(raw["learner"]["learner_model_param"]["base_score"]).strip("[]"))
        for t in trees:
            off = len(feat)
            roots.append(off)
            lc, rc = t["left_children"], t["right_children"]
            for i in range(len(lc)):
                leaf = lc[i] == -1
                feat.append(-1 if leaf else t["split_indices"][i])
                thr.append(0.0 if leaf else float(np.float32(t["split_conditions"][i])))
                left.append(-1 if leaf else lc[i] + off)
                right.append(-1 if leaf else rc[i] + off)
                value.append(float(t["split_conditions"][i]) if leaf else 0.0)
        return TreeTable(*map(np.asarray, (feat, thr, left, right, value, roots)), base=base, scale=1.0, cmp_le=False)
    if isinstance(model, RandomForestRegressor):
        for est in model.estimators_:
            tr = est.tree_
            off = len(feat)
            roots.append(off)
            for i in range(tr.node_count):
                leaf = tr.children_left[i] == -1
                feat.append(-1 if leaf else int(tr.feature[i]))
                thr.append(0.0 if leaf else float(tr.threshold[i]))
                left.append(-1 if leaf else int(tr.children_left[i]) + off)
                right.append(-1 if leaf else int(tr.children_right[i]) + off)
                value.append(float(tr.value[i].ravel()[0]) if leaf else 0.0)
        return TreeTable(*map(np.asarray, (feat, thr, left, right, value, roots)), base=0.0,
                         scale=1.0 / len(model.estimators_), cmp_le=True)
    raise TypeError(type(model))


# ------------------------------------------------------------------ C99
def _arr(ctype: str, name: str, vals, fmt) -> str:
    body = ",".join(fmt(v) for v in vals)
    return f"static const {ctype} {name}[{len(vals)}] = {{{body}}};\n"


def write_c(table: TreeTable, m: dict, version: str, out_dir: Path) -> dict:
    """m: MPC/guardrail limits (u_abs_max, b_abs_max kW). Returns file sizes."""
    out_dir.mkdir(parents=True, exist_ok=True)
    nf = len(POLICY_FEATURES)
    thr_t = "double" if table.cmp_le else "float"
    thr_fmt = (lambda v: repr(float(v))) if table.cmp_le else (lambda v: f"{float(np.float32(v))!r}f")
    h = f"""/* hess_policy.h: VoltSplit distilled power-split policy {version}
 * Generated by model-training/src/voltsplit/export.py. Do not edit.
 * Streaming controller for the vehicle ECU: call hess_ctrl_step() once per second.
 */
#ifndef HESS_POLICY_H
#define HESS_POLICY_H
#ifdef __cplusplus
extern "C" {{
#endif

#define HESS_POLICY_VERSION "{version}"
#define HESS_POLICY_N_FEATURES {nf}
#define HESS_POLICY_N_TREES {len(table.roots)}
#define HESS_POLICY_N_NODES {table.n_nodes}

typedef struct {{
    float p_hist[10];   /* last 10 P_req samples (kW), newest at index (head-1) */
    float v_hist[3];    /* last 3 speeds (m/s) */
    int   n;            /* samples seen */
    int   head;
    float pbat_prev_kw;
}} hess_ctrl_state_t;

typedef struct {{
    float p_sc_w;        /* supercap power command at the DC bus (W, + = discharge) */
    float p_bat_w;       /* resulting battery power (W) */
    unsigned char flags; /* bit0 fallback (invalid model output), bit1 limited */
}} hess_ctrl_out_t;

void  hess_ctrl_init(hess_ctrl_state_t *s);
float hess_policy_predict(const float x[HESS_POLICY_N_FEATURES]);
hess_ctrl_out_t hess_ctrl_step(hess_ctrl_state_t *s, float p_req_w, float speed_ms, float soc_sc, float soc_bat);

#ifdef __cplusplus
}}
#endif
#endif
"""
    c = [
        f'/* hess_policy.c: generated, {version}. Pure C99, no heap. */\n#include <math.h>\n#include "hess_policy.h"\n\n',
        f"#define U_ABS_MAX_KW {m['u_abs_max']!r}f\n#define B_ABS_MAX_KW {m['b_abs_max']!r}f\n#define FALLBACK_TH_KW 18.0f\n\n",
        _arr("short", "F", table.feat.tolist(), str),
        _arr(thr_t, "T", table.thr.tolist(), thr_fmt),
        _arr("int", "L", table.left.tolist(), str),
        _arr("int", "R", table.right.tolist(), str),
        _arr("float", "V", table.value.tolist(), lambda v: f"{float(np.float32(v))!r}f"),
        _arr("int", "ROOTS", table.roots.tolist(), str),
        f"""
float hess_policy_predict(const float x[HESS_POLICY_N_FEATURES]) {{
    double s = 0.0;
    int t;
    for (t = 0; t < HESS_POLICY_N_TREES; ++t) {{
        int n = ROOTS[t];
        while (F[n] >= 0) {{
            n = ((({thr_t})x[F[n]]) {'<=' if table.cmp_le else '<'} T[n]) ? L[n] : R[n];
        }}
        s += (double)V[n];
    }}
    return (float)({table.base!r} + s * {table.scale!r});
}}

void hess_ctrl_init(hess_ctrl_state_t *s) {{
    int i;
    for (i = 0; i < 10; ++i) s->p_hist[i] = 0.0f;
    for (i = 0; i < 3; ++i) s->v_hist[i] = 0.0f;
    s->n = 0; s->head = 0; s->pbat_prev_kw = 0.0f;
}}

static float hist(const hess_ctrl_state_t *s, int lag) {{ /* lag 0 = newest */
    int k = lag < s->n ? lag : s->n - 1;
    return s->p_hist[(s->head - 1 - k + 20) % 10];
}}

hess_ctrl_out_t hess_ctrl_step(hess_ctrl_state_t *s, float p_req_w, float speed_ms, float soc_sc, float soc_bat) {{
    hess_ctrl_out_t o;
    float x[HESS_POLICY_N_FEATURES];
    float p = p_req_w / 1000.0f, mean = 0.0f, m2 = 0.0f, var, u, lo, hi, v1, v2;
    int i, cnt;
    if (s->n == 0) {{ for (i = 0; i < 3; ++i) s->v_hist[i] = speed_ms; }}
    v1 = s->v_hist[0]; v2 = s->n >= 2 ? s->v_hist[1] : v1;
    s->p_hist[s->head] = p; s->head = (s->head + 1) % 10; if (s->n < 1000000) s->n++;
    cnt = s->n < 10 ? s->n : 10;
    for (i = 0; i < cnt; ++i) {{ float q = hist(s, i); mean += q; m2 += q * q; }}
    mean /= (float)cnt; var = m2 / (float)cnt - mean * mean; if (var < 0.0f) var = 0.0f;
    x[0] = p;
    for (i = 1; i <= {LAGS}; ++i) x[i] = hist(s, i);
    x[{LAGS + 1}] = speed_ms; x[{LAGS + 2}] = speed_ms - v1; x[{LAGS + 3}] = v1; x[{LAGS + 4}] = v2;
    x[{LAGS + 5}] = mean; x[{LAGS + 6}] = sqrtf(var);
    x[{LAGS + 7}] = soc_sc; x[{LAGS + 8}] = soc_bat; x[{LAGS + 9}] = s->pbat_prev_kw;
    s->v_hist[1] = s->v_hist[0]; s->v_hist[0] = speed_ms;

    o.flags = 0;
    u = hess_policy_predict(x);
    if (u != u || u > 1e4f || u < -1e4f) {{          /* guardrail: invalid → rule-based fallback */
        u = p > FALLBACK_TH_KW ? p - FALLBACK_TH_KW : (p < 0.0f ? p : 0.0f);
        o.flags |= 1u;
    }}
    lo = p - B_ABS_MAX_KW; if (lo < -U_ABS_MAX_KW) lo = -U_ABS_MAX_KW;
    hi = p + B_ABS_MAX_KW; if (hi >  U_ABS_MAX_KW) hi =  U_ABS_MAX_KW;
    if (hi < lo) hi = lo;
    if (u < lo) {{ u = lo; o.flags |= 2u; }}
    if (u > hi) {{ u = hi; o.flags |= 2u; }}
    s->pbat_prev_kw = p - u;
    o.p_sc_w = u * 1000.0f;
    o.p_bat_w = p_req_w - o.p_sc_w;
    return o;
}}
""",
    ]
    (out_dir / "hess_policy.h").write_text(h, encoding="utf-8")
    (out_dir / "hess_policy.c").write_text("".join(c), encoding="utf-8")
    return {"hess_policy.h": len(h.encode()), "hess_policy.c": len("".join(c).encode())}


# ------------------------------------------------------------------ TypeScript
def write_ts(path: Path, const_name: str, payload: dict, doc: str) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = (
        f"// GENERATED by model-training/src/voltsplit/export.py; do not edit.\n// {doc}\n"
        f"import type {{ TreeTable }} from \"../ml\";\n\n"
        if "table" in payload else
        f"// GENERATED by model-training/src/voltsplit/export.py; do not edit.\n// {doc}\n\n"
    )
    body = json.dumps(payload, separators=(",", ":"))
    if "table" in payload:
        text += f"export const {const_name} = {body} as const as unknown as {{ version: string; features: string[]; table: TreeTable; [k: string]: unknown }};\n"
    else:
        text += f"export const {const_name} = {body} as const;\n"
    path.write_text(text, encoding="utf-8")
    return len(text.encode())
