/** Generates supabase/migrations/0002_seed.sql from the frontend's built-in presets (single source of truth). */
import { writeFileSync } from "node:fs";
import * as cyclesMod from "../../frontend/src/lib/hess/cycles";
import * as presetsMod from "../../frontend/src/lib/hess/presets";

// Frontend files load as CommonJS here; named exports may sit under `default`.
type C = typeof cyclesMod; type P = typeof presetsMod;
const { BUILTIN_CYCLES } = ((cyclesMod as unknown as { default?: C }).default ?? cyclesMod) as C;
const { BUILTIN_VEHICLES } = ((presetsMod as unknown as { default?: P }).default ?? presetsMod) as P;

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: number[]) => `'{${a.map((x) => Number(x.toFixed(4))).join(",")}}'::real[]`;

let sql = `-- GENERATED by scripts/gen-seed.ts; do not edit by hand.\n-- Built-in vehicles and synthetic drive cycles shared by all users.\n\n`;
for (const v of BUILTIN_VEHICLES) {
  sql += `insert into public.vehicles (id, owner_id, name, description, config, is_builtin)
values (${q(v.id)}, null, ${q(v.name)}, ${q(v.description)}, ${q(JSON.stringify(v.config))}::jsonb, true)
on conflict (id) do update set name = excluded.name, description = excluded.description, config = excluded.config;\n\n`;
}
for (const c of BUILTIN_CYCLES) {
  sql += `insert into public.drive_cycles (id, owner_id, name, description, source, speed_ms)
values (${q(c.id)}, null, ${q(c.name)}, ${q(c.description)}, 'synthetic', ${arr(c.speedMs)})
on conflict (id) do update set name = excluded.name, description = excluded.description, speed_ms = excluded.speed_ms;\n\n`;
}
writeFileSync(new URL("../supabase/migrations/0002_seed.sql", import.meta.url), sql);
console.log(`seed: ${BUILTIN_VEHICLES.length} vehicles, ${BUILTIN_CYCLES.length} cycles`);
