import type { HessConfig } from "./model";

/**
 * Generates the ECU safety-guardrail layer as dependency-free C99.
 * The distilled ML policy's command always passes through this function, which
 * enforces hard limits and falls back to a rule-based split if the model output
 * is invalid (problem statement: "safety guardrail fallbacks").
 */
export function guardrailC(cfg: HessConfig, vehicleName: string): string {
  const b = cfg.battery, s = cfg.supercap;
  const vNom = (b.seriesCells * (b.cellOcvMin + b.cellOcvMax)) / 2;
  const f = (x: number, d = 1) => `${x.toFixed(d)}f`;
  return `/*
 * hess_guardrail.h: generated by VoltSplit for "${vehicleName}"
 * Hard limits applied to every power-split command before it reaches the
 * DC/DC converter. Pure C99, no dynamic memory, no libm dependency.
 */
#ifndef HESS_GUARDRAIL_H
#define HESS_GUARDRAIL_H

#define HESS_BAT_I_MAX_A        ${f(b.maxCurrentA)}
#define HESS_BAT_V_NOM_V        ${f(vNom)}
#define HESS_BAT_SOC_MIN        ${f(b.socMin, 3)}
#define HESS_BAT_SOC_MAX        ${f(b.socMax, 3)}
#define HESS_SC_I_MAX_A         ${f(s.maxCurrentA)}
#define HESS_SC_V_MAX_V         ${f(s.vMax)}
#define HESS_SC_V_MIN_V         ${f(s.vMax * s.vMinRatio)}
#define HESS_SC_SOC_EMPTY       0.02f
#define HESS_SC_SOC_FULL        0.98f
#define HESS_FALLBACK_P_TH_W    18000.0f   /* rule-based fallback threshold */

typedef struct {
    float p_sc_w;        /* supercap power command at the DC bus (W, + = discharge) */
    float p_bat_w;       /* resulting battery power (W) */
    unsigned char flags; /* bit0 fallback, bit1 SC limited, bit2 battery limited */
} hess_cmd_t;

static inline float hess_clampf(float x, float lo, float hi) {
    return x < lo ? lo : (x > hi ? hi : x);
}

/* p_sc_model_w may be NaN/Inf if the model misbehaves: x != x detects NaN. */
static inline hess_cmd_t hess_guardrail(float p_req_w, float p_sc_model_w,
                                        float soc_sc, float v_sc, float soc_bat) {
    hess_cmd_t out = {0.0f, 0.0f, 0u};
    float p = p_sc_model_w;
    (void)soc_bat;

    if (p != p || p > 1e7f || p < -1e7f) {             /* invalid → fallback */
        p = p_req_w > HESS_FALLBACK_P_TH_W ? p_req_w - HESS_FALLBACK_P_TH_W
          : (p_req_w < 0.0f ? p_req_w : 0.0f);
        out.flags |= 1u;
    }

    /* Supercap current limit and usable energy window */
    {
        float p_sc_max = HESS_SC_I_MAX_A * hess_clampf(v_sc, HESS_SC_V_MIN_V, HESS_SC_V_MAX_V);
        float lim = hess_clampf(p, -p_sc_max, p_sc_max);
        if (soc_sc <= HESS_SC_SOC_EMPTY && lim > 0.0f) lim = 0.0f;
        if (soc_sc >= HESS_SC_SOC_FULL  && lim < 0.0f) lim = 0.0f;
        if (lim != p) out.flags |= 2u;
        p = lim;
    }

    /* Battery current limit: shift the excess back onto the supercap */
    {
        float p_bat_max = HESS_BAT_I_MAX_A * HESS_BAT_V_NOM_V;
        float p_bat = p_req_w - p;
        if (p_bat >  p_bat_max) { p = p_req_w - p_bat_max; out.flags |= 4u; }
        if (p_bat < -p_bat_max) { p = p_req_w + p_bat_max; out.flags |= 4u; }
    }

    out.p_sc_w = p;
    out.p_bat_w = p_req_w - p;
    return out;
}

#endif /* HESS_GUARDRAIL_H */
`;
}
